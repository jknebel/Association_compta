
import { TransactionComment } from './frontend/types/rbac';

export enum AccountType {
  INCOME = 'PRODUIT',
  EXPENSE = 'CHARGE',
  MIXED = 'MIXTE',
  ASSET = 'ACTIF',
  LIABILITY = 'PASSIF'
}

export interface Account {
  id: string;
  code: string;
  label: string;
  description: string;
  type: AccountType;
  isMembership: boolean; // Special flag for the mandatory membership account
  parentId?: string; // ID of the parent account for aggregation
  icon?: string; // Lucide icon name
  autoGenerated?: boolean; // True for auto-created level 3 sub-accounts (MIXTE split)
  iaContext?: string; // Specific instructions for this account
  initialBalance?: number;
  closingBalance?: number;
}

export enum TransactionStatus {
  PENDING = 'PENDING',
  REVIEW_NEEDED = 'REVIEW_NEEDED',
  PENDING_REVIEW = 'PENDING_REVIEW',
  PROPOSED = 'PROPOSED', // Affectation proposée par le vérificateur
  APPROVED = 'APPROVED',
  ARCHIVED = 'ARCHIVED'
}

export interface TransactionVerifierProposal {
  proposedAccountId: string;
  note?: string;
  verifierUid: string;
  verifierName: string;
  verifierEmail: string;
  proposedAt: number;
}

export interface Transaction {
  id: string;
  date: string;
  description: string;
  amount: number; // Positive for Credit (Income), Negative for Debit (Expense)
  accountId?: string;
  status: TransactionStatus;
  notes?: string;
  detectedMemberName?: string; // If extracted by AI
  simplifiedDescription?: string; // Cleaned version by AI
  fullRawText?: string; // Literal text from bank statement
  receiptUrl?: string; // URL to the uploaded receipt image
  receiptFileName?: string; // Name of the receipt file
  comments?: TransactionComment[]; // Comments & audit notes
  verifierProposal?: TransactionVerifierProposal; // Proposition du vérificateur en attente de validation par le caissier
}

export type ReceiptExpenseType = 'DEBIT_CARD' | 'REIMBURSEMENT';
export type ReceiptReimbursementStatus = 'PENDING' | 'REIMBURSED' | 'REJECTED';
export type ReceiptTransferStatus = 'PENDING_ACCEPTANCE' | 'ACCEPTED';

// WEB-03 : traçabilité du transfert d'une pièce vers une autre comptabilité
export interface ReceiptTransferRequest {
  fromComptaId: string;
  fromComptaName: string;
  toComptaId: string;
  toComptaName: string;
  requestedByUid: string;
  requestedByName: string;
  requestedByEmail?: string;
  requestedAt: number;
  note?: string;
  status: ReceiptTransferStatus;
  isReturn?: boolean; // true si la pièce a été renvoyée vers sa comptabilité d'origine
  acceptedAt?: number;
  acceptedByUid?: string;
  acceptedByName?: string;
}

export interface Receipt {
  id: string;
  url: string;
  fileName: string;
  uploadDate: string;
  extractedDate?: string;
  extractedAmount?: number;
  isAnalyzed: boolean;
  linkedTransactionId?: string | null;
  // WEB-02 Fields
  expenseType?: ReceiptExpenseType;
  description?: string;
  merchantName?: string;
  submittedByUid?: string;
  submittedByName?: string;
  submittedByEmail?: string;
  reimbursementIban?: string;
  reimbursementStatus?: ReceiptReimbursementStatus;
  reimbursedAt?: number;
  reimbursedByUid?: string;
  reimbursedByName?: string;
  // WEB-03 Fields
  transferRequest?: ReceiptTransferRequest;
  transferHistory?: ReceiptTransferRequest[];
}

export interface Member {
  id: string;
  name: string;
  hasPaid: boolean;
  paymentDate?: string;
  amountPaid: number;
}

export interface ProcessingResult {
  transactions: Transaction[];
  suggestedAccounts: Account[];
  logs: string[];
}

export interface ChatMessage {
  role: 'user' | 'model';
  text: string;
  isThinking?: boolean;
}